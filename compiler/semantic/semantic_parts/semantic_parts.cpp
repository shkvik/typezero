Diagnostics::ResultTaken SemanticParts::walkProgram() {
  auto &modules = state.file.modules;
  auto declaredTypes = std::vector<std::vector<Stmt *>>(modules.size());

  declaration.names.openScope();
  library.dispatch.prepareLibraries(state.file);
  library.dispatch.declareErrorTypes();
  library.fs.declareFsClasses();
  declaration.prelude.declarePrelude();
  flow.changes.rememberAssigned(state.file);
  state.declaration.modules.prepareModules(int(modules.size()));
  for (Module *module : modules) {
    declaration.modules.declareNames(module);
  }
  for (Module *module : modules) {
    declaration.modules.useModule(module);
    declaredTypes[module->order] = declaration.types.declareModuleTypes(module);
  }
  for (Module *module : modules) {
    declaration.modules.resolveImports(module);
    runTasks();
  }
  declaration.modules.bindAllImports(modules);
  for (Module *module : modules) {
    declaration.modules.useModule(module);
    declaration.types.resolveTypes(declaredTypes[module->order]);
    runTasks();
  }
  for (Module *module : modules) {
    declaration.modules.useModule(module);
    for (Stmt *item : module->file.items) {
      declaration.functions.declareItemFunction(item, module);
      declaration.classes.declareItemMethods(item, module);
      runTasks();
    }
  }
  declaration.modules.bindAllImports(modules);
  state.declaration.classes.markMethodsDeclared();
  generics.classes.fillUnfilledInstances();
  runTasks();
  code.classes.markLateOverrides(state.file);
  state.walk.tasks.pushTask(StartLinkClasses{});
  runTasks();
  auto classes = state.declaration.classes.getClasses();
  for (ClassDecl *classDecl : llvm::reverse(classes)) {
    state.walk.tasks.pushTask(CompleteClass{.classDecl = classDecl});
  }
  runTasks();
  for (Module *module : modules) {
    declaration.modules.exportsOf(module);
  }
  library.reflect.rememberWriters(state.file);
  declaration.names.rememberNamesInFunctions(state.file);
  declaration.modules.noteImportsInFunctions(state.file);

  inference.cycles.findProgramCycles();

  state.walk.flow.replaceFlow(Flow());
  for (Module *module : llvm::reverse(modules)) {
    state.walk.tasks.pushTask(StartTopLevel{.module = module});
  }
  runTasks();
  state.declaration.modules.markTopLevelDone();
  declaration.modules.bindAllImports(modules);
  for (Module *module : llvm::reverse(modules)) {
    state.walk.tasks.pushTask(StartModuleBodies{.module = module});
  }
  runTasks();
  auto liftedFunctions = state.code.variables.getLiftedFunctions();
  for (FunctionDecl *lifted : llvm::reverse(liftedFunctions)) {
    state.walk.tasks.pushTask(StartLiftedFunction{.functionDecl = lifted});
  }
  runTasks();
  for (Module *module : llvm::reverse(modules)) {
    if (module->declaration != nullptr) {
      state.walk.tasks.pushTask(StartDeclarationFile{.module = module});
    }
  }
  runTasks();
  library.events.finishSentEmits();
  runTasks();

  do {
    generics.copies.pushInstanceTasks();
    code.classes.pushLateClassTasks();
    runTasks();
  } while (state.code.late.hasUncheckedLateClasses());
  code.classes.walkConstructorCalls();
  code.variables.reportUncheckedResults();

  library.reflect.finishReflection();
  library.events.walkErrorListeners();
  library.events.walkDroppedListeners();
  for (Module *module : modules) {
    declaration.modules.useModule(module);
    code.variables.reportUntyped();
  }
  declaration.names.closeScope();
  library.fs.rememberNativeError();
  runTasks();
  declaration.links.numberClasses();
  code.classes.rememberEmittedLateClasses();

  return state.diagnostics.take();
}

void SemanticParts::runTasks() {
  while (state.walk.tasks.hasTasks()) {
    auto task = state.walk.tasks.takeTask();
    runTask(task);
  }
}

