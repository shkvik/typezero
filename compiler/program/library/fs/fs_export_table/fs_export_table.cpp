std::optional<FsExport> FsExportTable::find(NodeModule module, llvm::StringRef name) {
  for (const FsExportInfo &info : kExports) {
    if (info.module == module && info.name == name) {
      return info.kind;
    }
  }

  return std::nullopt;
}

bool FsExportTable::isFunction(NodeModule module, llvm::StringRef name) {
  auto kind = FsExportTable::find(module, name);

  return kind == FsExport::FUNCTION || kind == FsExport::HANDLE_FUNCTION;
}

