#include "compiler/load/token/token.h"

namespace tz {

const char *tokSpelling(Tok kind) {
  switch (kind) {
  case Tok::Eof:
    return "end of file";
  case Tok::Identifier:
    return "identifier";
  case Tok::IntLiteral:
    return "integer literal";
  case Tok::FloatLiteral:
    return "number literal";
  case Tok::StringLiteral:
    return "string literal";
  case Tok::TemplateString:
  case Tok::TemplateHead:
    return "template literal";
  case Tok::TemplateMiddle:
  case Tok::TemplateTail:
    return "'}'";
  case Tok::RegexLiteral:
    return "regular expression";
  case Tok::KwAs:
    return "'as'";
  case Tok::KwBreak:
    return "'break'";
  case Tok::KwCase:
    return "'case'";
  case Tok::KwConst:
    return "'const'";
  case Tok::KwContinue:
    return "'continue'";
  case Tok::KwDebugger:
    return "'debugger'";
  case Tok::KwDefault:
    return "'default'";
  case Tok::KwDelete:
    return "'delete'";
  case Tok::KwDo:
    return "'do'";
  case Tok::KwElse:
    return "'else'";
  case Tok::KwEnum:
    return "'enum'";
  case Tok::KwFalse:
    return "'false'";
  case Tok::KwFor:
    return "'for'";
  case Tok::KwFunction:
    return "'function'";
  case Tok::KwIf:
    return "'if'";
  case Tok::KwIn:
    return "'in'";
  case Tok::KwLet:
    return "'let'";
  case Tok::KwNew:
    return "'new'";
  case Tok::KwReturn:
    return "'return'";
  case Tok::KwSwitch:
    return "'switch'";
  case Tok::KwTrue:
    return "'true'";
  case Tok::KwTypeof:
    return "'typeof'";
  case Tok::KwVar:
    return "'var'";
  case Tok::KwVoid:
    return "'void'";
  case Tok::KwWhile:
    return "'while'";
  case Tok::LParen:
    return "'('";
  case Tok::RParen:
    return "')'";
  case Tok::LBrace:
    return "'{'";
  case Tok::RBrace:
    return "'}'";
  case Tok::LBracket:
    return "'['";
  case Tok::RBracket:
    return "']'";
  case Tok::Comma:
    return "','";
  case Tok::Semi:
    return "';'";
  case Tok::Colon:
    return "':'";
  case Tok::Dot:
    return "'.'";
  case Tok::Ellipsis:
    return "'...'";
  case Tok::Question:
    return "'?'";
  case Tok::QuestionQuestion:
    return "'??'";
  case Tok::QuestionDot:
    return "'?.'";
  case Tok::Arrow:
    return "'=>'";
  case Tok::At:
    return "'@'";
  case Tok::Plus:
    return "'+'";
  case Tok::Minus:
    return "'-'";
  case Tok::Star:
    return "'*'";
  case Tok::StarStar:
    return "'**'";
  case Tok::Slash:
    return "'/'";
  case Tok::Percent:
    return "'%'";
  case Tok::PlusPlus:
    return "'++'";
  case Tok::MinusMinus:
    return "'--'";
  case Tok::Amp:
    return "'&'";
  case Tok::Pipe:
    return "'|'";
  case Tok::Caret:
    return "'^'";
  case Tok::Tilde:
    return "'~'";
  case Tok::Bang:
    return "'!'";
  case Tok::AmpAmp:
    return "'&&'";
  case Tok::PipePipe:
    return "'||'";
  case Tok::Shl:
    return "'<<'";
  case Tok::Shr:
    return "'>>'";
  case Tok::UShr:
    return "'>>>'";
  case Tok::Less:
    return "'<'";
  case Tok::LessEq:
    return "'<='";
  case Tok::Greater:
    return "'>'";
  case Tok::GreaterEq:
    return "'>='";
  case Tok::EqEq:
    return "'=='";
  case Tok::EqEqEq:
    return "'==='";
  case Tok::BangEq:
    return "'!='";
  case Tok::BangEqEq:
    return "'!=='";
  case Tok::Assign:
    return "'='";
  case Tok::PlusAssign:
    return "'+='";
  case Tok::MinusAssign:
    return "'-='";
  case Tok::StarAssign:
    return "'*='";
  case Tok::StarStarAssign:
    return "'**='";
  case Tok::SlashAssign:
    return "'/='";
  case Tok::PercentAssign:
    return "'%='";
  case Tok::AmpAssign:
    return "'&='";
  case Tok::PipeAssign:
    return "'|='";
  case Tok::CaretAssign:
    return "'^='";
  case Tok::ShlAssign:
    return "'<<='";
  case Tok::ShrAssign:
    return "'>>='";
  case Tok::UShrAssign:
    return "'>>>='";
  case Tok::QuestionQuestionAssign:
    return "'??='";
  case Tok::AmpAmpAssign:
    return "'&&='";
  case Tok::PipePipeAssign:
    return "'||='";
  }

  return "token";
}

} // namespace tz
