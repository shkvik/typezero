// Generates tls_roots.h: the root certificates that https trusts (tls.c, docs/net.md, section 4),
// those node embeds (its src/node_root_certs.h, Mozilla's list from NSS), taken from the node
// that runs this, as tls.rootCertificates gives them:
//
//   cd runtime/library/tls/tls
//   node gen_tls_roots.mjs > tls_roots.h
//
// Their DER, one after the other, is compressed with raw deflate, which tls.c inflates with the
// zlib of the runtime the first time a program makes a connection of https.

import { X509Certificate } from "node:crypto";
import { rootCertificates } from "node:tls";
import { deflateRawSync } from "node:zlib";

const certificates = rootCertificates.map((pem) => new X509Certificate(pem));
const der = Buffer.concat(certificates.map((c) => c.raw));
const packed = deflateRawSync(der, { level: 9 });

// The name of each, for whoever reads the header: its CN, or its O and OU.
const nameOf = (c) => {
  const parts = Object.fromEntries(c.subject.split("\n").map((line) => line.split("=", 2)));
  return parts.CN ?? [parts.O, parts.OU].filter(Boolean).join(", ");
};

const lines = [
  `// Generated by gen_tls_roots.mjs from node ${process.version}. Do not edit.`,
  "//",
  `// The ${certificates.length} root certificates of Mozilla that node embeds: ${der.length} bytes`,
  `// of DER, compressed with raw deflate to ${packed.length}.`,
  "//",
  ...certificates.map((c) => `//   ${nameOf(c)}`),
  "",
  `#define TLS_ROOTS_COUNT ${certificates.length}`,
  `#define TLS_ROOTS_SIZE ${der.length}`,
  "",
  `static const unsigned char tls_roots[${packed.length}] = {`,
];
for (let i = 0; i < packed.length; i += 16) {
  const row = [...packed.subarray(i, i + 16)].map((b) => `0x${b.toString(16).padStart(2, "0")},`);
  lines.push(`    ${row.join(" ")}`);
}
lines.push("};", "");
process.stdout.write(lines.join("\n"));
