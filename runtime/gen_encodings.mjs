const names = new Map();
for (const label of labels) {
  try {
    names.set(label, new TextDecoder(label).encoding);
  } catch {
    // An encoding node does not decode.
  }
}

// A single-byte encoding decodes each byte by itself to one code unit.
const multiByte = new Set(["utf-8", "utf-16le", "utf-16be", "gbk", "gb18030", "big5", "euc-jp",
  "iso-2022-jp", "shift_jis", "euc-kr"]);
const single = [...new Set(names.values())].filter((n) => !multiByte.has(n)).sort();

const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");
const lines = [];
lines.push(`// Generated by gen_encodings.mjs from Node.js ${process.version}. Do not edit.`);
lines.push("//");
lines.push("// Included by the runtime (buffer.c), which uses only the labels, and by the");
lines.push("// compiler (src/codegen/codegen_bytes.cpp), which puts the tables of the");
lines.push("// encodings a program names into it.");
lines.push("");
lines.push("#ifndef TZ_ENCODINGS_H");
lines.push("#define TZ_ENCODINGS_H");
lines.push("");
lines.push("#include <stdint.h>");
lines.push("#include <string.h>");
lines.push("");
lines.push("// A single-byte encoding: what each byte from 0x80 on decodes to; 0xFFFD for");
lines.push("// a byte the encoding does not map.");
lines.push("typedef struct TzEncodingTable {");
lines.push("  const char *name;");
lines.push("  uint16_t high[128];");
lines.push("} TzEncodingTable;");
lines.push("");
lines.push("// The labels, lowercase, and the name of the encoding of each.");
lines.push("static const char *const tz_encoding_labels[][2] = {");
for (const [label, name] of names) lines.push(`    {"${label}", "${name}"},`);
lines.push("};");
lines.push("");
lines.push("// The name of the encoding of a lowercase label without whitespace, or NULL.");
lines.push("static inline const char *tz_encoding_name(const char *label) {");
lines.push("  for (size_t i = 0; i < sizeof tz_encoding_labels / sizeof tz_encoding_labels[0]; ++i)");
lines.push("    if (strcmp(tz_encoding_labels[i][0], label) == 0)");
lines.push("      return tz_encoding_labels[i][1];");
lines.push("  return NULL;");
lines.push("}");
lines.push("");
lines.push("// Whether node decodes the encoding of that name with more than a byte for");
lines.push("// some characters, which tz does not support yet.");
lines.push("static inline int tz_encoding_multi_byte(const char *name) {");
lines.push("  static const char *const names[] = {" +
  [...multiByte].filter((n) => !n.startsWith("utf")).map((n) => `"${n}"`).join(", ") + "};");
lines.push("  for (size_t i = 0; i < sizeof names / sizeof names[0]; ++i)");
lines.push("    if (strcmp(names[i], name) == 0)");
lines.push("      return 1;");
lines.push("  return 0;");
lines.push("}");
lines.push("");
lines.push("#define TZ_ENCODING_TABLES(X) \\");
single.forEach((name, k) => {
  const decoder = new TextDecoder(name, { fatal: true });
  const high = [];
  for (let b = 0x80; b <= 0xff; b++) {
    try {
      const s = decoder.decode(new Uint8Array([b]));
      if (s.length !== 1) throw new Error(`${name}: byte ${b} gives ${s.length} units`);
      high.push(s.charCodeAt(0));
    } catch (e) {
      if (!(e instanceof TypeError)) throw e;
      high.push(0xfffd);
    }
  }
  const rows = [];
  for (let i = 0; i < 128; i += 8) rows.push(high.slice(i, i + 8).map(hex).join(", "));
  lines.push(`  X("${name}", ${rows.join(", ")})` + (k + 1 < single.length ? " \\" : ""));
});
lines.push("");
lines.push("#endif");
console.log(lines.join("\n"));
