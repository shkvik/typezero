// Generates number_tables.h: the powers of 5 that the shortest formatting of
// doubles in number.c multiplies by (the algorithm Ryū of Ulf Adams, 2018).
//
//   cd runtime/core/number
//   node gen_number_tables.mjs > number_tables.h
//
// pow5[i] is 5^i scaled to its top 125 bits; pow5_inv[i] is 2^(bits(5^i) - 1 +
// 125) / 5^i plus one, 1 / 5^i scaled to 125 bits and rounded up. Each is a
// pair of 64-bit words, the low one first. The sizes cover every exponent of
// a double.

const BITS = 125n;
const POW5_COUNT = 326;
const POW5_INV_COUNT = 342;

const bitLength = (x) => BigInt(x.toString(2).length);
const mask64 = (1n << 64n) - 1n;
const hex = (x) => `0x${x.toString(16).toUpperCase().padStart(16, "0")}u`;
const pair = (x) => `{${hex(x & mask64)}, ${hex(x >> 64n)}}`;

const lines = [
  "// Generated by gen_number_tables.mjs. Do not edit.",
  "",
  `#define POW5_COUNT ${POW5_COUNT}`,
  `#define POW5_INV_COUNT ${POW5_INV_COUNT}`,
  `#define POW5_BITS ${BITS}`,
  "",
  "static const uint64_t pow5[POW5_COUNT][2] = {",
];
for (let i = 0; i < POW5_COUNT; i++) {
  const p = 5n ** BigInt(i);
  const shift = bitLength(p) - BITS;
  const top = shift >= 0n ? p >> shift : p << -shift;
  lines.push(`    ${pair(top)},`);
}
lines.push("};", "", "static const uint64_t pow5_inv[POW5_INV_COUNT][2] = {");
for (let i = 0; i < POW5_INV_COUNT; i++) {
  const p = 5n ** BigInt(i);
  const inv = (1n << (bitLength(p) - 1n + BITS)) / p + 1n;
  if (inv >> 128n) throw new Error(`pow5_inv[${i}] does not fit in 128 bits`);
  lines.push(`    ${pair(inv)},`);
}
lines.push("};", "");
process.stdout.write(lines.join("\n"));
